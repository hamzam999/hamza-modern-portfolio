// Build-time extraction of technology icons. Run: `npm run icons` (after changing the ICONS list below).
// Sources (nothing is drawn by hand): Simple Icons (CC0-1.0) first, Devicon (MIT) for brands Simple Icons no longer ships.
// Writes
//   public/art/tech-sprite.svg       one <symbol> per icon, monochrome (fill inherits currentColor), referenced with <use>
//   src/styles/tech-icons.css        brand colour per icon (only where it has >= 3:1 on the sheet), applied on hover and focus
//   src/content/tech-icons.json      id -> {source, key, hex, title}; read by the unit test, never imported by the client
//   docs/ICON_LICENSES.md            licences and versions
// The full packages stay in devDependencies and never enter the client bundle: the page only references the sprite.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const si = require('simple-icons');
const siPkg = JSON.parse(readFileSync(path.join(ROOT, 'node_modules/simple-icons/package.json'), 'utf8'));
const dev = require('devicon/devicon.json');
const devPkg = JSON.parse(readFileSync(path.join(ROOT, 'node_modules/devicon/package.json'), 'utf8'));

/** id (used in the sprite and in src/content/tech.ts) -> source. `s:` = Simple Icons export, `d:` = Devicon folder/variant. */
const ICONS = {
  react: 's:siReact', nextjs: 's:siNextdotjs', typescript: 's:siTypescript', javascript: 's:siJavascript', angular: 's:siAngular',
  redux: 's:siRedux', reactrouter: 's:siReactrouter', tanstack: 's:siReactquery', tailwind: 's:siTailwindcss', vite: 's:siVite',
  html5: 's:siHtml5', css3: 'd:css3/plain', bootstrap: 's:siBootstrap', shadcn: 's:siShadcnui', threejs: 's:siThreedotjs',
  gsap: 's:siGreensock', webgl: 's:siWebgl', shopify: 's:siShopify', remix: 's:siRemix', wordpress: 's:siWordpress',
  woocommerce: 's:siWoocommerce', php: 's:siPhp', nodejs: 's:siNodedotjs', express: 's:siExpress', postgresql: 's:siPostgresql',
  prisma: 's:siPrisma', zod: 's:siZod', jwt: 's:siJsonwebtokens', docker: 's:siDocker', aws: 'd:amazonwebservices/plain',
  github: 's:siGithub', githubactions: 's:siGithubactions', git: 's:siGit', bitbucket: 's:siBitbucket', jira: 's:siJira',
  figma: 's:siFigma', playwright: 'd:playwright/plain', erpnext: 's:siErpnext', python: 's:siPython', solana: 's:siSolana',
  ethereum: 's:siEthereum', ethers: 's:siEthers', wagmi: 's:siWagmi', walletconnect: 's:siWalletconnect', pwa: 's:siPwa',
  n8n: 's:siN8n', claude: 's:siClaude', cursor: 's:siCursor', vscode: 'd:vscode/plain', postman: 's:siPostman', framer: 's:siFramer',
  cloudflare: 's:siCloudflare', youtube: 's:siYoutube', graphql: 's:siGraphql', postiz: 's:siPostiz', reactnative: 'd:reactnative/original',
};

const lin = (c) => ((c /= 255) <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (hex) => { const n = parseInt(hex.replace('#', ''), 16); return 0.2126 * lin(n >> 16) + 0.7152 * lin((n >> 8) & 255) + 0.0722 * lin(n & 255); };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const SHEET = '#F3F0EA';

const symbols = [];
const meta = {};
const css = [];
for (const [id, spec] of Object.entries(ICONS)) {
  const [kind, key] = [spec[0], spec.slice(2)];
  if (kind === 's') {
    const icon = si[key];
    if (!icon) throw new Error(`Simple Icons has no ${key}`);
    symbols.push(`<symbol id="${id}" viewBox="0 0 24 24"><path d="${icon.path}"/></symbol>`);
    meta[id] = { source: 'simple-icons', key, title: icon.title, hex: `#${icon.hex}` };
  } else {
    const [name, variant] = key.split('/');
    const file = path.join(ROOT, 'node_modules/devicon/icons', name, `${name}-${variant}.svg`);
    const svg = readFileSync(file, 'utf8');
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1] ?? '0 0 128 128';
    const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s(fill|class|id|style)="[^"]*"/g, '').trim();
    if (/<(style|image|defs|linearGradient|radialGradient|mask|clipPath)/.test(body)) throw new Error(`${file}: unsupported markup (gradient, style or mask)`);
    symbols.push(`<symbol id="${id}" viewBox="${viewBox}">${body}</symbol>`);
    const hex = dev.find((d) => d.name === name)?.color ?? '#000000';
    meta[id] = { source: 'devicon', key, title: name, hex: hex.length === 4 ? `#${[...hex.slice(1)].map((c) => c + c).join('')}` : hex };
  }
  const hex = meta[id].hex.toUpperCase();
  if (ratio(hex, SHEET) >= 3 && hex !== '#000000' && !/^#(0A0A0A|181717|191919)$/.test(hex)) css.push(`.tech[data-i="${id}"] { --brand: ${hex}; }`);
}

writeFileSync(path.join(ROOT, 'public/art/tech-sprite.svg'), `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by scripts/build-icons.mjs from Simple Icons (CC0-1.0) and Devicon (MIT). Do not edit. Brand logos are trademarks of their owners. -->\n${symbols.join('\n')}\n</svg>\n`);
writeFileSync(path.join(ROOT, 'src/styles/tech-icons.css'), `/* Generated by scripts/build-icons.mjs. Brand colours from Simple Icons and Devicon, kept only where they reach 3:1 on the sheet (#F3F0EA).\n   Icons are monochrome by default and take the brand colour on hover and keyboard focus; the technology name is always visible text. */\n${css.join('\n')}\n`);
writeFileSync(path.join(ROOT, 'src/content/tech-icons.json'), JSON.stringify(meta, null, 1) + '\n');
writeFileSync(path.join(ROOT, 'docs/ICON_LICENSES.md'), `# Technology icons

Icons are extracted at build time by \`npm run icons\` (\`scripts/build-icons.mjs\`) into \`public/art/tech-sprite.svg\`. Nothing is drawn by hand and neither package enters the client bundle.

| Source | Version | Licence | Used for |
|---|---|---|---|
| [Simple Icons](https://simpleicons.org) | ${siPkg.version} | CC0-1.0 | ${Object.values(meta).filter((m) => m.source === 'simple-icons').length} icons |
| [Devicon](https://devicon.dev) | ${devPkg.version} | MIT | ${Object.values(meta).filter((m) => m.source === 'devicon').map((m) => m.key).join(', ')} |

Logos are trademarks of their respective owners; they are shown only to name the technology used. Technologies with no icon in either library (for example Paperclip, Hermes and Antigravity) show a neutral initial chip, never an invented logo.
`);
console.log(`icons: ${symbols.length} symbols, ${css.length} brand colours, sprite ${(readFileSync(path.join(ROOT, 'public/art/tech-sprite.svg')).length / 1024).toFixed(1)} KB`);
