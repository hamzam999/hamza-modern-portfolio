// Converts the giant kanji (KANJI in src/content/jp.ts) to SVG path data at weight 800 (plan 3.8).
import subsetFont from 'subset-font';
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'media-src/fonts/NotoSansJP-VariableFont_wght.ttf';
const jpSource = readFileSync('src/content/jp.ts', 'utf8');
const kanjiPart = jpSource.split('export const KANJI')[1] ?? '';
const chars = [...new Set([...kanjiPart].filter((c) => c.codePointAt(0) > 0x7f))];

const ttf = await subsetFont(readFileSync(SRC), chars.join(''), {
  targetFormat: 'truetype',
  variationAxes: { wght: 800 },
});
const font = opentype.parse(ttf.buffer.slice(ttf.byteOffset, ttf.byteOffset + ttf.byteLength));
const upem = font.unitsPerEm;
const EM_TOP = Math.round(upem * 0.88); // CJK em box: 880 above baseline, 120 below

const glyphs = chars.map((char) => {
  const g = font.charToGlyph(char);
  // y-down path, baseline at EM_TOP, so the em box spans y 0..upem.
  const d = g.getPath(0, EM_TOP, upem).toPathData(1);
  return { char, d, advance: g.advanceWidth ?? upem };
});

const body = `/** GENERATED by scripts/kanji-paths.mjs. Do not edit. Noto Sans JP 800 outlines as SVG paths (plan 3.8). */
export const KANJI_UPEM = ${upem};
export interface KanjiGlyph { readonly char: string; readonly d: string; readonly advance: number }
export const KANJI_GLYPHS: Readonly<Record<string, KanjiGlyph>> = {
${glyphs.map((g) => `  ${JSON.stringify(g.char)}: { char: ${JSON.stringify(g.char)}, d: ${JSON.stringify(g.d)}, advance: ${g.advance} },`).join('\n')}
};
`;
writeFileSync('src/content/kanji-paths.ts', body);
console.log(`kanji-paths.ts: ${glyphs.length} glyphs, ${(body.length / 1024).toFixed(1)} KB, upem ${upem}`);
