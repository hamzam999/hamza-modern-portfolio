// Urdu assets (npm run urdu). Source: media-src/fonts/NotoNastaliqUrdu-700-arabic.woff2 (Noto Nastaliq Urdu, SIL OFL).
//  1. public/fonts/noto-nastaliq-urdu-700-subset.<hash>.woff2 : subset to the glyphs of src/content/urdu.ts, GSUB/GPOS kept
//     so letters join; the hashed name is written into src/styles/fonts.css.
//  2. scripts/og/urdu-paths.json : words shaped with HarfBuzz and converted to outlines (Open Graph cards).
//  3. src/components/brand/hamza-path.ts : the hamza letter as one outline for the logo, favicon and stamps.
import subsetFont from 'subset-font';
import * as hb from 'harfbuzzjs';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, statSync } from 'node:fs';

const SRC = 'media-src/fonts/NotoNastaliqUrdu-700-arabic.woff2';
const OUT_DIR = 'public/fonts';
const CSS = 'src/styles/fonts.css';

const source = readFileSync('src/content/urdu.ts', 'utf8');
const words = [...source.matchAll(/'([؀-ۿ]+)'/g)].map((m) => m[1]);
if (words.length === 0) throw new Error('No Urdu words found in src/content/urdu.ts');
const chars = [...new Set([...words.join(''), 'ء', '‌', '‍'])].sort();
const text = chars.join('');
const input = readFileSync(SRC);

// 1. Web font subset (layout tables kept by default, so init/medi/fina forms and Nastaliq positioning survive).
const woff2 = await subsetFont(input, text, { targetFormat: 'woff2' });
const hash = createHash('sha1').update(woff2).digest('hex').slice(0, 8);
const name = `noto-nastaliq-urdu-700-subset.${hash}.woff2`;
mkdirSync(OUT_DIR, { recursive: true });
for (const f of readdirSync(OUT_DIR)) if (/^noto-nastaliq-urdu-700-subset.*\.woff2$/.test(f)) rmSync(`${OUT_DIR}/${f}`);
writeFileSync(`${OUT_DIR}/${name}`, woff2);
const css = readFileSync(CSS, 'utf8').replace(/\/fonts\/noto-nastaliq-urdu-700-subset[\w.]*\.woff2/, `/fonts/${name}`);
writeFileSync(CSS, css);
console.log(`${OUT_DIR}/${name}: ${statSync(`${OUT_DIR}/${name}`).size} bytes, ${chars.length} codepoints`);

// 2 + 3. Shape with HarfBuzz (sfnt copy of the same subset).
const sfnt = await subsetFont(input, text, { targetFormat: 'sfnt' });
const face = new hb.Face(new hb.Blob(sfnt.buffer.slice(sfnt.byteOffset, sfnt.byteOffset + sfnt.byteLength)));
const font = new hb.Font(face);

function transform(d, dx, dy) {
  // hb paths use absolute M L Q C Z with y up; flip to y down and translate.
  const out = [];
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const re = /([MLQCZ])([^MLQCZ]*)/g;
  for (const [, cmd, args] of d.matchAll(re)) {
    const n = args.trim() ? args.trim().split(/[\s,]+/).map(Number) : [];
    const pts = [];
    for (let i = 0; i < n.length; i += 2) {
      const x = n[i] + dx, y = -(n[i + 1] + dy);
      pts.push([x, y]);
      minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y);
    }
    out.push({ cmd, pts });
  }
  return { out, minX, minY, maxX, maxY };
}

function outline(str) {
  const buf = new hb.Buffer();
  buf.addText(str);
  buf.guessSegmentProperties();
  hb.shape(font, buf);
  const infos = buf.getGlyphInfos();
  const pos = buf.getGlyphPositions();
  let pen = 0;
  const parts = [];
  infos.forEach((g, i) => {
    const p = pos[i];
    parts.push(transform(font.glyphToPath(g.codepoint), pen + p.xOffset, p.yOffset));
    pen += p.xAdvance;
  });
  const valid = parts.filter((p) => Number.isFinite(p.minX));
  const minX = Math.min(...valid.map((p) => p.minX)), maxX = Math.max(...valid.map((p) => p.maxX));
  const minY = Math.min(...valid.map((p) => p.minY)), maxY = Math.max(...valid.map((p) => p.maxY));
  const r = (v) => Math.round(v * 10) / 10;
  const d = valid
    .flatMap((p) => p.out.map((c) => c.cmd + c.pts.map(([x, y]) => `${r(x - minX)} ${r(y - minY)}`).join(' ')))
    .join('');
  buf.destroy?.();
  return { d, w: Math.round(maxX - minX), h: Math.round(maxY - minY), glyphs: infos.length };
}

const shaped = {};
for (const w of words) shaped[w] = outline(w);
mkdirSync('scripts/og', { recursive: true });
writeFileSync('scripts/og/urdu-paths.json', JSON.stringify(shaped));
for (const [w, o] of Object.entries(shaped)) console.log(`shaped ${w}: ${o.glyphs} glyphs, ${o.w}x${o.h}`);

const hamza = outline('ء');
mkdirSync('src/components/brand', { recursive: true });
writeFileSync(
  'src/components/brand/hamza-path.ts',
  `/** GENERATED by scripts/build-urdu.mjs from Noto Nastaliq Urdu (SIL OFL). The Urdu letter hamza as one outline. Do not edit. */\nexport const HAMZA = { d: ${JSON.stringify(hamza.d)}, w: ${hamza.w}, h: ${hamza.h} } as const;\n`,
);
console.log(`hamza: ${hamza.w}x${hamza.h}, ${hamza.d.length} chars of path`);
